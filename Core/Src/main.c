/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();          // Инициализация DMA строго ПЕРЕД АЦП и UART!
  MX_USART2_UART_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  
  /* USER CODE BEGIN 2 */
  // 1. Запуск АЦП в циклическом режиме DMA на весь размер буфера
  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_buffer, ADC_BUF_SIZE);

  // 2. Запуск таймера TIM2, который аппаратно пинает АЦП с частотой 1 кГц
  HAL_TIM_Base_Start(&htim2);
  /* USER CODE END 2 */

  /* INFINITE LOOP */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

        /* USER CODE BEGIN 3 */
    if (data_ready_flag != 0)
    {
      uint8_t *tx_ptr;
      
      if (data_ready_flag == 1)
      {
        tx_ptr = (uint8_t*)&adc_buffer;
      }
      else
      {
        tx_ptr = (uint8_t*)&adc_buffer[HALF_BUF_SIZE];
      }

      // Сбрасываем флаг прерывания АЦП
      data_ready_flag = 0;

      // Ждём, пока UART ФИЗИЧЕСКИ не завершит передачу прошлых байт.
      // (USART_ISR_TC) — это железный флаг самого кремниевого кристалла.
      // Пока он равен 0, передатчик аппаратно занят.
      while ((huart2.Instance->ISR & USART_ISR_TC) == 0) 
      {
        // Защитный таймаут на случай непредвиденного сбоя на линии
        if (huart2.ErrorCode != HAL_UART_ERROR_NONE) {
            HAL_UART_AbortTransmit(&huart2);
            break;
        }
      }

      // Принудительно возвращаем внутренний программный статус HAL в READY,
      // чтобы библиотека не паниковала и разрешила запуск DMA
      huart2.gState = HAL_UART_STATE_READY;

      // Запускаем аппаратный DMA USART2 на отправку пачки байт
      HAL_UART_Transmit_DMA(&huart2, tx_ptr, HALF_BUF_SIZE * 2);
    }
    /* USER CODE END 3 */

  }
}

